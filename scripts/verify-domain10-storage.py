def http_json(
    method: str,
    path: str,
    payload: dict | list | None = None,
    query_params: dict[str, Any] | None = None,
    token: str | None = None,
) -> tuple[int, dict[str, str], Any]:
    url = BASE_URL + path
    if query_params:
        url += "?" + urllib.parse.urlencode(query_params)
    body = json.dumps(payload).encode("utf-8") if payload is not None else None
    headers = {"Accept": "application/json"}
    if payload is not None:
        headers["Content-Type"] = "application/json"
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, data=body, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = resp.read()
            parsed = json.loads(data.decode("utf-8")) if data else None
            return resp.status, dict(resp.headers), parsed
    except urllib.error.HTTPError as e:
        err_body = e.read()
        try:
            parsed = json.loads(err_body.decode("utf-8"))
        except Exception:
            parsed = {"raw": err_body.decode("utf-8", errors="replace")}
        return e.code, dict(e.headers), parsed


def http_multipart(
    method: str,
    path: str,
    fields: dict[str, str],
    files: dict[str, tuple[str, bytes, str]],
    token: str | None = None,
) -> tuple[int, dict[str, str], Any]:
    boundary = f"----WebKitFormBoundary{uuid.uuid4().hex}"
    buf = io.BytesIO()

    for k, v in fields.items():
        buf.write(f"--{boundary}\r\n".encode("utf-8"))
        buf.write(f'Content-Disposition: form-data; name="{k}"\r\n\r\n'.encode("utf-8"))
        buf.write(f"{v}\r\n".encode("utf-8"))

    for k, (filename, content, mime) in files.items():
        buf.write(f"--{boundary}\r\n".encode("utf-8"))
        buf.write(f'Content-Disposition: form-data; name="{k}"; filename="{filename}"\r\n'.encode("utf-8"))
        buf.write(f"Content-Type: {mime}\r\n\r\n".encode("utf-8"))
        buf.write(content)
        buf.write(b"\r\n")

    buf.write(f"--{boundary}--\r\n".encode("utf-8"))
    body = buf.getvalue()

    url = BASE_URL + path
    headers = {
        "Accept": "application/json",
        "Content-Type": f"multipart/form-data; boundary={boundary}",
        "Content-Length": str(len(body)),
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"

    req = urllib.request.Request(url, data=body, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = resp.read()
            parsed = json.loads(data.decode("utf-8")) if data else None
            return resp.status, dict(resp.headers), parsed
    except urllib.error.HTTPError as e:
        err_body = e.read()
        try:
            parsed = json.loads(err_body.decode("utf-8"))
        except Exception:
            parsed = {"raw": err_body.decode("utf-8", errors="replace")}
        return e.code, dict(e.headers), parsed


def http_get_raw(path: str, token: str | None = None) -> tuple[int, dict[str, str], bytes]:
    url = BASE_URL + path if path.startswith("/") else path
    headers = {}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers, method="GET")
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            return resp.status, dict(resp.headers), resp.read()
    except urllib.error.HTTPError as e:
        return e.code, dict(e.headers), e.read()


def scan_clam(data: bytes) -> bytes:
    s = socket.socket()
    s.connect(("127.0.0.1", 3310))
    s.sendall(b"zINSTREAM\0")
    chunk_size = 8192
    for i in range(0, len(data), chunk_size):
        chunk = data[i : i + chunk_size]
        s.sendall(struct.pack(">I", len(chunk)) + chunk)
    s.sendall(struct.pack(">I", 0))
    res = s.recv(1024)
    s.close()
    return res


